var updateGolden = flag.Bool("update", false, "update golden files in testdata")

// generatedIDPattern matches resource IDs generated by the provider.
var generatedIDPattern = regexp.MustCompile(`tf-[0-7][0-9A-HJKMNP-TV-Z]{25}`)

// newProviderMeta configures the provider against srv, as Terraform would,
// and returns the client passed to resource functions.
func newProviderMeta(t *testing.T, srv *fakebindplane.Server, raw map[string]any) *client.BindPlane {
	t.Helper()

	if raw == nil {
		raw = map[string]any{}
	}
	if _, ok := raw["remote_url"]; !ok {
		raw["remote_url"] = srv.URL
	}

	d := schema.TestResourceDataRaw(t, Configure().Schema, raw)
	meta, diags := providerConfigure(d, nil)
	require.False(t, diags.HasError(), "%v", diags)
	return meta.(*client.BindPlane)
}

// lastApplyBody returns the body of the most recent apply request, with
// generated resource IDs replaced by "<generated>".
func lastApplyBody(t *testing.T, srv *fakebindplane.Server) string {
	t.Helper()
	req := srv.LastRequest(http.MethodPost, "/v1/apply")
	require.NotNil(t, req, "expected an apply request")
	return generatedIDPattern.ReplaceAllString(string(req.Body), "<generated>")
}

// requireGoldenJSON compares actual with the JSON in testdata/name. Run
// tests with -update to rewrite the golden file.
func requireGoldenJSON(t *testing.T, name, actual string) {
	t.Helper()
	path := filepath.Join("testdata", name)
	if *updateGolden {
		var v any
		require.NoError(t, json.Unmarshal([]byte(actual), &v))
		data, err := json.MarshalIndent(v, "", "  ")
		require.NoError(t, err)
		require.NoError(t, os.WriteFile(path, append(data, '\n'), 0o600))
	}
	expected, err := os.ReadFile(path) // #nosec G304 test golden file
	require.NoError(t, err)
	require.JSONEq(t, string(expected), actual)
}

func TestProviderConfigure_auth(t *testing.T) {
	cases := []struct {
		name string
		auth fakebindplane.Auth
		raw  map[string]any
	}{
		{
			name: "api key",
			auth: fakebindplane.Auth{APIKey: "legacy-key"},
			raw:  map[string]any{"api_key": "legacy-key"},
		},
		{
			name: "scoped api key",
			auth: fakebindplane.Auth{APIKey: "bps_abc.def", AccountID: "01ACCOUNT"},
			raw:  map[string]any{"api_key": "bps_abc.def", "account_id": "01ACCOUNT"},
		},
		{
			name: "username and password",
			auth: fakebindplane.Auth{Username: "user", Password: "pass"},
			raw:  map[string]any{"username": "user", "password": "pass"},
		},
	}

	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			srv := fakebindplane.New(t, fakebindplane.WithAuth(tc.auth))
			bindplane := newProviderMeta(t, srv, tc.raw)

			config, err := bindplane.Configuration("missing")
			require.NoError(t, err)
			require.Nil(t, config)
		})
	}

	t.Run("wrong credentials", func(t *testing.T) {
		srv := fakebindplane.New(t, fakebindplane.WithAuth(fakebindplane.Auth{Username: "user", Password: "pass"}))
		bindplane := newProviderMeta(t, srv, map[string]any{"username": "user", "password": "wrong"})

		_, err := bindplane.Configuration("missing")
		require.ErrorContains(t, err, "401 Unauthorized")
	})
}

func TestProviderConfigure_tls(t *testing.T) {
	t.Run("certificate authority", func(t *testing.T) {
		srv := fakebindplane.New(t, fakebindplane.WithTLS(nil))
		bindplane := newProviderMeta(t, srv, map[string]any{"tls_certificate_authority": srv.CAFile})

		_, err := bindplane.Configuration("missing")
		require.NoError(t, err)
	})

	t.Run("skip verify", func(t *testing.T) {
		srv := fakebindplane.New(t, fakebindplane.WithTLS(nil))
		bindplane := newProviderMeta(t, srv, map[string]any{"tls_skip_verify": true})

		_, err := bindplane.Configuration("missing")
		require.NoError(t, err)
	})

	t.Run("untrusted certificate", func(t *testing.T) {
		srv := fakebindplane.New(t, fakebindplane.WithTLS(nil))
		bindplane := newProviderMeta(t, srv, nil)

		_, err := bindplane.Configuration("missing")
		require.ErrorContains(t, err, "certificate")
	})

	t.Run("mutual tls", func(t *testing.T) {
		cert := fakebindplane.NewClientCertificate(t)
		srv := fakebindplane.New(t, fakebindplane.WithTLS(&tls.Config{
			ClientAuth: tls.RequireAndVerifyClientCert,
			ClientCAs:  cert.CAPool,
		}))

		bindplane := newProviderMeta(t, srv, map[string]any{
			"tls_certificate_authority": srv.CAFile,
			"tls_certificate":           cert.CertFile,
			"tls_private_key":           cert.KeyFile,
		})
		_, err := bindplane.Configuration("missing")
		require.NoError(t, err)

		// The client certificate is ignored without a private key
		bindplane = newProviderMeta(t, srv, map[string]any{
			"tls_certificate_authority": srv.CAFile,
			"tls_certificate":           cert.CertFile,
		})
		_, err = bindplane.Configuration("missing")
		require.ErrorContains(t, err, "certificate required")
	})

	t.Run("missing certificate authority file", func(t *testing.T) {
		d := schema.TestResourceDataRaw(t, Configure().Schema, map[string]any{
			"remote_url":                "https://localhost:3001",
			"tls_certificate_authority": filepath.Join(t.TempDir(), "missing.crt"),
		})
		_, diags := providerConfigure(d, nil)
		require.True(t, diags.HasError())
		require.Contains(t, diags[0].Summary, "failed to initialize bindplane client")
	})
}
