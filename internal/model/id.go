package model

import (
	"crypto/rand"
	"encoding/binary"
	"time"
)

// crockford is the alphabet of Crockford's base32, used to encode ULIDs
const crockford = "0123456789ABCDEFGHJKMNPQRSTVWXYZ"

// NewResourceID returns a new resource ID. IDs are ULIDs, like the IDs
// generated by Bindplane: a 48 bit millisecond timestamp followed by 80
// random bits, encoded as 26 characters of Crockford's base32.
func NewResourceID() string {
	var id [16]byte
	binary.BigEndian.PutUint64(id[:8], uint64(time.Now().UnixMilli())<<16) // #nosec G115 the timestamp is positive
	// crypto/rand.Read never returns an error
	_, _ = rand.Read(id[6:])

	// Encode the 128 bit ID five bits at a time, from the least significant bits
	hi := binary.BigEndian.Uint64(id[:8])
	lo := binary.BigEndian.Uint64(id[8:])
	var out [26]byte
	for i := len(out) - 1; i >= 0; i-- {
		out[i] = crockford[lo&0x1f]
		lo = lo>>5 | hi<<59
		hi >>= 5
	}
	return string(out[:])
}
